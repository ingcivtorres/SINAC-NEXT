export function useLanguage() {
  const [language, setLanguage] = React.useState(() => {
    const stored = typeof window !== 'undefined' ? localStorage.getItem('sinac_language') : null;
    return supportedLanguages.some(item => item.code === stored) ? stored : 'es';
  });

  React.useEffect(() => {
    const handleLanguageChange = () => {
      const stored = localStorage.getItem('sinac_language') || 'es';
      const lang = supportedLanguages.some(item => item.code === stored) ? stored : 'es';
      setLanguage(lang);
    };

    window.addEventListener('sinac:language-changed', handleLanguageChange);
    return () => window.removeEventListener('sinac:language-changed', handleLanguageChange);
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  
  return {
    language,
    t: (key) => translations[language]?.[key] || translations.es[key] || key,
    setLanguage: (lang) => {
      const nextLanguage = supportedLanguages.some(item => item.code === lang) ? lang : 'es';
      localStorage.setItem('sinac_language', nextLanguage);
      window.dispatchEvent(new Event('sinac:language-changed'));
    }
  };
}
